<?php

namespace App\Enums;

/** Тема оформления, которую выбрал пользователь (меню пользователя, ADR-0025). */
enum Theme: string
{
    /** Светлая — по умолчанию (решение PM 21.10, LATER-89, п. 8). */
    case Light = 'light';

    case Dark = 'dark';

    /** Как в системе: светлая или тёмная по настройке устройства, меняется на ходу. */
    case System = 'system';
}
