<?php

namespace App\Enums;

/**
 * Область карточек роли (docs/adr/0024-rights-2.md; бывший флаг own_cards_only, ADR-0008): какие карточки
 * пространства видит и с какими действует источник доступа с этой ролью.
 */
enum CardScope: string
{
    /** Все карточки пространства. */
    case All = 'all';

    /** Только свои: где пользователь заказчик, ответственный или участник. */
    case Own = 'own';
}
