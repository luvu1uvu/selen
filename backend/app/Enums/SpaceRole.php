<?php

namespace App\Enums;

/**
 * Роль в API пространств: участники, группы, my_role, журнал событий (docs/adr/0005-space-access.md).
 * С «Прав 2.0» (ADR-0024) права даёт не она, а стандартная роль выдачи (StandardRole) — набор прав каталога;
 * пара «роль + только свои карточки» переводится в неё StandardRole::fromLegacy(). Проверки доступа — только по
 * правам каталога (App\Enums\Permission), не по этой роли.
 * Системная роль (UserRole) доступа к содержимому пространств не даёт.
 */
enum SpaceRole: string
{
    /** «Администратор»: всё в пространстве — доски, колонки, дорожки, участники и их роли. */
    case Admin = 'admin';

    /** «Редактор»: создаёт, редактирует и перемещает карточки. Структуру и участников не трогает. */
    case Editor = 'editor';

    /** «Комментатор»: чтение, комментарии и файлы. */
    case Commenter = 'commenter';

    /**
     * Роль управляет доступом — к ней неприменим режим «только свои карточки» и её не выдают «Всем сотрудникам»
     * (правила API, как CHECK ролей в БД).
     */
    public function canManageSpace(): bool
    {
        return $this === self::Admin;
    }
}
